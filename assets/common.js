// ── Переключение языка ──
function setLang(lang) {
  const dict = I18N[lang] || I18N.ru;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key] !== undefined) {
      if (dict[key].indexOf('<') !== -1) el.innerHTML = dict[key];
      else el.textContent = dict[key];
    }
  });
  document.documentElement.lang = lang;
  document.querySelectorAll('.lang-switch button').forEach(b => {
    b.classList.toggle('active', b.getAttribute('data-lang') === lang);
  });
  try { localStorage.setItem('itg_lang', lang); } catch (e) {}
}

// ── Разбор Markdown ──
function parseMd(text) {
  const m = text.match(/^---\s*\n([\s\S]*?)\n---\s*\n?([\s\S]*)$/);
  if (!m) return { body: text };
  const data = { body: (m[2] || '').trim() };
  m[1].split('\n').forEach(line => {
    const i = line.indexOf(':');
    if (i < 0) return;
    const key = line.slice(0, i).trim();
    let val = line.slice(i + 1).trim();
    val = val.replace(/^["']|["']$/g, '');
    if (val === 'true') val = true;
    else if (val === 'false') val = false;
    data[key] = val;
  });
  return data;
}

// ── Загрузка контента из папки ──
async function loadFolder(folder, indexFile) {
  try {
    const r = await fetch('/' + indexFile + '?v=' + Date.now());
    if (!r.ok) return [];
    const names = await r.json();
    if (!Array.isArray(names)) return [];
    const items = await Promise.all(names.map(async name => {
      try {
        const res = await fetch(`/${folder}/${name}?v=` + Date.now());
        return res.ok ? parseMd(await res.text()) : null;
      } catch (e) { return null; }
    }));
    return items.filter(Boolean);
  } catch (e) { return []; }
}

function formatDate(d) {
  if (!d) return '';
  const dt = new Date(d);
  if (isNaN(dt)) return d;
  return dt.toLocaleDateString('ru-RU', { day: '2-digit', month: 'long', year: 'numeric' });
}

function escapeHtml(s) {
  return String(s).replace(/[&<>"']/g, c =>
    ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
}

// ── Инициализация на каждой странице ──
document.addEventListener('DOMContentLoaded', () => {
  document.querySelectorAll('.lang-switch button').forEach(btn => {
    btn.addEventListener('click', () => setLang(btn.getAttribute('data-lang')));
  });
  let saved = 'ru';
  try { saved = localStorage.getItem('itg_lang') || 'ru'; } catch (e) {}
  setLang(saved);

  const io = new IntersectionObserver((entries) => {
    entries.forEach(e => { if (e.isIntersecting) e.target.classList.add('show'); });
  }, { threshold: 0.15 });
  document.querySelectorAll('.reveal').forEach(el => io.observe(el));
});
